#!/usr/bin/env python3
# Golden signs for src/tests/fossil_test_implicit_points.f90 (issue #65), from an exact rational evaluation.
# Usage: python3 scripts/gen_implicit_points_golden.py  (writes implicit_points_golden.txt in the current directory;
# the committed copy is src/tests/implicit_points_golden.txt). Values are written with repr (round-trip exact).
import random, struct
from fractions import Fraction as F
random.seed(20261106)
def R(): return random.uniform(-1,1)
def nudge(x,k):  # move x by k ulps
    b=struct.unpack('<q',struct.pack('<d',x))[0]
    if x<0: b-=k
    else: b+=k
    return struct.unpack('<d',struct.pack('<q',b))[0]
def sub(a,b): return [a[i]-b[i] for i in range(3)]
def cross(a,b): return [a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0]]
def dot(a,b): return sum(a[i]*b[i] for i in range(3))
def lpi(p,q,r,s,t):
    p,q,r,s,t=[[F(x) for x in v] for v in (p,q,r,s,t)]
    n=cross(sub(s,r),sub(t,r)); w=dot(n,sub(q,p)); tt=dot(n,sub(r,p))
    return [p[i]+tt/w*(q[i]-p[i]) for i in range(3)]
def o3d(a,b,c,d):  # Shewchuk orient3d(a,b,c,d) = det[a-d;b-d;c-d]
    a,b,c,d=[[F(x) for x in v] for v in (a,b,c,d)]
    A=sub(a,d);B=sub(b,d);C=sub(c,d)
    return dot(A,cross(B,C))
def o2d(p,q,r,drop):
    i=(drop)%3; j=(drop+1)%3
    return (p[i]-r[i])*(q[j]-r[j])-(p[j]-r[j])*(q[i]-r[i])
def sg(x): return (x>0)-(x<0)
out=[]
# kind 1: orient3d(LPI, a,b,c): a,b,c = plane through the LPI point, one vertex nudged by k ulps
for n in range(60):
    p=[R() for _ in range(3)]; q=[R() for _ in range(3)]
    r=[R() for _ in range(3)]; s=[R() for _ in range(3)]; t=[R() for _ in range(3)]
    X=lpi(p,q,r,s,t)
    if any(abs(x)>2 for x in X): continue
    Xa=[float(x) for x in X]
    a=[R() for _ in range(3)]; b=[R() for _ in range(3)]
    # c: a point making (a,b,c) nearly through X: c = X + (X - a) * 0.7 rounded, then nudged
    c=[float(F(Xa[i])+(F(Xa[i])-F(a[i]))*F(7,10)) for i in range(3)]
    k=random.choice([0,1,2,5,50])
    c[random.randrange(3)]=c[random.randrange(3)]  # kept: it consumes the random stream of the committed golden file
    idx=random.randrange(3); c[idx]=nudge(c[idx],k*random.choice([-1,1]))
    e=sg(o3d(a,b,c,X))
    naive=sg(o3d(a,b,c,Xa))
    out.append(('O3',p+q+r+s+t+a+b+c,e,naive))
# kind 2: orient2d(LPI1, LPI2, explicit e) with LPIs on nearly the same line through e
for n in range(60):
    p=[R() for _ in range(3)]; q=[R() for _ in range(3)]
    pl1=[[R() for _ in range(3)] for _ in range(3)]; pl2=[[R() for _ in range(3)] for _ in range(3)]
    q2=list(q); idx=random.randrange(3); q2[idx]=nudge(q2[idx],random.choice([0,1,3,20]))
    X1=lpi(p,q,*pl1); X2=lpi(p,q2,*pl2)
    if any(abs(x)>3 for x in X1+X2): continue
    drop=random.randrange(3)
    e=sg(o2d(X1,X2,[F(x) for x in p],drop))
    naive=sg(o2d([F(float(x)) for x in X1],[F(float(x)) for x in X2],[F(x) for x in p],drop))
    out.append(('O2',p+q+pl1[0]+pl1[1]+pl1[2]+p+q2+pl2[0]+pl2[1]+pl2[2],(e,drop),naive))
with open('implicit_points_golden.txt','w') as f:
    f.write('# fossil_test_implicit_points golden (issue #65): exact rational signs; generated by a Python Fraction script\n')
    for kind,vals,e,naive in out:
        if kind=='O3':
            f.write('O3 %d %d %s\n'%(e,naive,' '.join(repr(v) for v in vals)))
        else:
            f.write('O2 %d %d %d %s\n'%(e[0],e[1],naive,' '.join(repr(v) for v in vals)))
print(len(out), sum(1 for o in out if (o[2] if o[0]=='O3' else o[2][0])!=o[3]), 'naive disagreements', sum(1 for o in out if (o[2] if o[0]=='O3' else o[2][0])==0),'zeros')
